import sys,unittest
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parents[2]/'tools'))
import native_gdn_log1p_numeric as L
N=L.N
def controls(x):
 u=N.add(0x3f800000,x);r=L.reference(x)
 if u==0x3f800000:return dict(zip(L.FIELDS,(r,x,u,0,0,0)))
 l=L.nearest(L.ideal_log(u));n=N.mul(l,x);d=N.add(u,0xbf800000);c=L.nearest(L.q(n)/L.q(d))
 return dict(zip(L.FIELDS,(r,c,u,l,n,d)))
def batch(x):return {k:[v]*256 for k,v in controls(x).items()}
class Tests(unittest.TestCase):
 def test_pinned_correct_rounding(self):
  # Independent known values and binade edges; not generated by compensated expression.
  for x,r in [(0,0),(0x80000000,0x80000000),(0x800000,0x800000),(0x30800000,0x30800000),(0x3f800000,0x3f317218),(0x40000000,0x3f8c9f54),(0x4e000000,0x41a0cf66)]:self.assertEqual(L.reference(x),r)
 def test_tiny_and_target_rejection(self):
  for x in (0,0x80000000,0x800000,0x30800000):
   v=batch(x);L.check_values([x]*256,v,'vulkan');v['result'][0]=0x3f800000
   with self.assertRaises(ValueError):L.check_values([x]*256,v,'vulkan')
 def test_primitive_valid_is_not_fidelity(self):
  x=0x34000000;v=batch(x);l=0x34c00000
  v['log']=[l]*256;v['numerator']=[N.mul(l,x)]*256;v['compensated']=[L.nearest(L.q(v['numerator'][0])/L.q(v['denominator'][0]))]*256;v['result']=v['compensated'][:]
  L.check_values([x]*256,v,'vulkan',False)
  with self.assertRaisesRegex(ValueError,'target'):L.check_values([x]*256,v,'vulkan')
 def test_common_wrong_outputs_rejected(self):
  for backend in ('native','vulkan'):
   v=batch(0x3f800000);v['result']=[0]*256
   with self.assertRaises(ValueError):L.check_values([0x3f800000]*256,v,backend)
 def test_boundaries(self):
  for x in (0x33800000,0x33800001,0x33ffffff,0x34000000,0x3f7fffff,0x3f800001,0x4e000000):L.check_values([x]*256,batch(x),'native')
  for x in (1,0x807fffff,0xbf800000,0x7f800000,0x7fc00000,0x4e000001):
   with self.assertRaises(ValueError):L.domain(x)
 def test_corrupt_order(self):
  v=batch(0x3f800000);v['denominator'][0]^=1
  with self.assertRaises(ValueError):L.check_values([0x3f800000]*256,v,'native')
if __name__=='__main__':unittest.main()
